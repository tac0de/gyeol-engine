/** Explicit adapters to the existing kernel. No image model, planner or generation loop. */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {randomUUID} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {assetRoot,assetPath,assetId,readAssetJson,hash} from './asset-paths.ts';
export type MediaAction='prepare'|'synthesize'|'publish'|'validate';
export type PixelAction='assemble'|'export'|'validate';
export interface VisualOptions {project:string;kernelBin:string;authorityRef:string}
export function createVisualTools(options:VisualOptions){
 const root=assetRoot(options.project);
 if(!path.isAbsolute(options.kernelBin)||!options.authorityRef.trim())throw Error('Explicit kernel executable and existing user decision reference required');
 function invoke(operation:string,inputs:Record<string,string>){
  const base=path.join(os.homedir(),'.local/state/paradox-visual-tools');fs.mkdirSync(base,{recursive:true,mode:0o700});
  const evidence=fs.mkdtempSync(path.join(base,'request-')),request=path.join(evidence,'request.json');
  fs.writeFileSync(request,JSON.stringify({schemaVersion:1,requestId:'visual-'+randomUUID(),phase:'ready',contract:{id:'game',version:1},operation,decisionRefs:[{kind:'user',ref:options.authorityRef}],unresolved:[],inputs}));
  const result=spawnSync(options.kernelBin,['catalog','execute','--request',request],{cwd:root,encoding:'utf8',timeout:120000,maxBuffer:4*1024*1024});
  fs.writeFileSync(path.join(evidence,'stdout.json'),result.stdout??'');fs.writeFileSync(path.join(evidence,'stderr.log'),result.stderr??'');
  if(result.error||result.status!==0)throw Error(`Visual operation failed: ${operation}; evidence ${evidence}`,{cause:result.error});
  const response=JSON.parse(result.stdout);if(response.status!=='completed')throw Error(`Visual operation incomplete; evidence ${evidence}`);
  if(!response.result||typeof response.result!=='object'||Array.isArray(response.result))throw Error(`Visual operation missing result; evidence ${evidence}`);
  return response.result;
 }
 function media(action:MediaAction,inputs:Record<string,string>){
  const fields={prepare:'briefPath',synthesize:'recipePath',publish:'manifestPath',validate:'bundlePath'} as const;
  const field=fields[action];if(!field||Object.keys(inputs).join(',')!==field)throw Error('Invalid explicit media operation');
  assetPath(root,inputs[field]);return invoke('game.media.'+action,{project:root,...inputs});
 }
 function pixel(action:PixelAction,planPath:string){
  if(!['assemble','export','validate'].includes(action))throw Error('Unknown pixel action');
  return invoke('game.animation.'+action,{project:root,planPath:assetPath(root,planPath)});
 }
 function retouch(patchPath:string){return invoke('game.animation.retouch',{project:root,patchPath:assetPath(root,patchPath)});}
 function pixelValue(planPath:string,gameId:string){
  const p=readAssetJson(root,planPath);assetId(p.id);assetId(gameId);
  if(typeof p.output!=='string'||!p.output.startsWith(`/assets/${gameId}/`))throw Error('Pixel output must belong to the consuming game');
  const prefix='public'+p.output,atlas=readAssetJson(root,prefix+'.json'),evidence=readAssetJson(root,prefix+'-export.json');
  const files=[planPath,evidence.source,prefix+'.png',prefix+'.json',prefix+'-production.json',prefix+'-export.json'];
  const inputs=Object.fromEntries(files.map(file=>[file,hash(fs.readFileSync(assetPath(root,file)))]));
  if(inputs[evidence.source]!==evidence.hashes?.source||inputs[prefix+'.png']!==evidence.hashes?.png||inputs[prefix+'.json']!==evidence.hashes?.atlas)throw Error('Stale native pixel output');
  const ids=p.frames.map((f:any)=>f.id);
  if(!Array.isArray(atlas.frames)||atlas.frames.length!==ids.length)throw Error('Pixel frame mapping mismatch');
  return {planPath,gameId,id:p.id,image:p.output+'.png',canvas:p.canvas,pivot:p.pivot,scale:p.scale??1,
   frames:atlas.frames.map((f:any,i:number)=>({id:ids[i],...f.frame,durationMs:f.duration})),clips:p.clips,inputs};
 }
 function registration(value:unknown){return '// Generated by engine tools/visual; edit native source and re-export.\nexport const sprite='+JSON.stringify(value,null,2)+' as const;\n';}
 function bindPixel(planPath:string,gameId:string,name:string,refresh=false){
  assetId(name);pixel('validate',planPath);
  const value=pixelValue(planPath,gameId),file=assetPath(root,`portal/games/${assetId(gameId)}/pixel-${name}.generated.ts`),content=registration(value);
  if(fs.existsSync(file)){if(fs.lstatSync(file).nlink!==1)throw Error('Aliased pixel registration rejected');if(fs.readFileSync(file,'utf8')===content)return value;if(!refresh)throw Error('Changed pixel binding; explicitly refresh registration');}
  fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content,{flag:refresh?'w':'wx'});return value;
 }
 function checkPixelBinding(gameId:string,name:string){
  const file=assetPath(root,`portal/games/${assetId(gameId)}/pixel-${assetId(name)}.generated.ts`),content=fs.readFileSync(file,'utf8');
  const match=content.match(/export const sprite=([\s\S]+) as const;\n$/);if(!match)throw Error('Invalid pixel binding');
  const stored=JSON.parse(match[1]);if(stored.gameId!==gameId||registration(pixelValue(stored.planPath,gameId))!==content)throw Error('Stale pixel binding');
  return {gameId,name,mechanicalStatus:'passed',visualReview:'unverified'};
 }
 return {media,pixel,retouch,bindPixel,checkPixelBinding};
}
